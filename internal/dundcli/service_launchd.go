package dundcli

import (
	"fmt"
	"html"
	"os"
	"os/exec"
	"path/filepath"
	"strconv"
	"strings"
)

// launchd runs dund as a LaunchAgent on macOS: the same verbs as systemd.
//
//	~/Library/LaunchAgents/com.iodesystems.<name>.plist
//
// The shape follows the systemd unit: KeepAlive.SuccessfulExit=false is
// Restart=on-failure (a clean stop stays stopped), ThrottleInterval is
// RestartSec, ExitTimeOut is TimeoutStopSec. launchd has no ExecStartPre, so
// `serve --check` runs at install only; dund refuses bad flags at start
// anyway. A LaunchAgent loads at login, and SuccessfulExit implies
// RunAtLoad, so an installed dund starts at login: --enable is implied.
//
// Output goes to <home>/dund.log (launchd has no journal for agents); `logs`
// follows it.
type launchd struct{}

func launchdLabel(name string) string { return "com.iodesystems." + name }

func (launchd) path(name string) (string, error) {
	home, err := os.UserHomeDir()
	if err != nil {
		return "", err
	}
	return filepath.Join(home, "Library", "LaunchAgents", launchdLabel(name)+".plist"), nil
}

func (launchd) render(name, execPath string, prefix []string, home string, serveArgs, envs []string) string {
	str := func(s string) string { return "<string>" + html.EscapeString(s) + "</string>" }
	args := []string{execPath}
	args = append(args, prefix...)
	args = append(args, "--home", home, "serve")
	args = append(args, serveArgs...)
	logf := filepath.Join(home, "dund.log")

	var b strings.Builder
	b.WriteString(`<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!-- Generated by ` + "`dun dund service install`" + `. Edits are overwritten on reinstall. -->
<plist version="1.0">
<dict>
`)
	fmt.Fprintf(&b, "\t<key>Label</key>%s\n", str(launchdLabel(name)))
	b.WriteString("\t<key>ProgramArguments</key>\n\t<array>\n")
	for _, a := range args {
		fmt.Fprintf(&b, "\t\t%s\n", str(a))
	}
	b.WriteString("\t</array>\n")
	fmt.Fprintf(&b, "\t<key>WorkingDirectory</key>%s\n", str(home))
	b.WriteString("\t<key>EnvironmentVariables</key>\n\t<dict>\n")
	fmt.Fprintf(&b, "\t\t<key>DUN_HOME</key>%s\n", str(home))
	for _, e := range envs {
		k, v, _ := strings.Cut(e, "=")
		fmt.Fprintf(&b, "\t\t<key>%s</key>%s\n", html.EscapeString(k), str(v))
	}
	b.WriteString("\t</dict>\n")
	b.WriteString("\t<key>KeepAlive</key>\n\t<dict>\n\t\t<key>SuccessfulExit</key>\n\t\t<false/>\n\t</dict>\n")
	b.WriteString("\t<key>ThrottleInterval</key>\n\t<integer>3</integer>\n")
	b.WriteString("\t<key>ExitTimeOut</key>\n\t<integer>30</integer>\n")
	fmt.Fprintf(&b, "\t<key>StandardOutPath</key>%s\n", str(logf))
	fmt.Fprintf(&b, "\t<key>StandardErrorPath</key>%s\n", str(logf))
	b.WriteString("</dict>\n</plist>\n")
	return b.String()
}

func launchctl(args ...string) ([]byte, error) {
	return exec.Command("launchctl", args...).CombinedOutput()
}

func guiDomain() string { return "gui/" + strconv.Itoa(os.Getuid()) }

func (l launchd) load(name, path string, _, start bool) error {
	if !start {
		fmt.Println("macOS: the LaunchAgent loads (and starts) at next login; `dun dund service start` starts it now")
		return nil
	}
	// A reinstall replaces a loaded agent: out with the old, in with the new.
	_, _ = launchctl("bootout", guiDomain()+"/"+launchdLabel(name))
	if out, err := launchctl("bootstrap", guiDomain(), path); err != nil {
		return fmt.Errorf("launchctl bootstrap %s: %v: %s", path, err, strings.TrimSpace(string(out)))
	}
	return nil
}

func (launchd) homeLine(home string) string {
	return "<key>DUN_HOME</key><string>" + html.EscapeString(home) + "</string>\n"
}

func (launchd) unload(name string) error {
	_, err := launchctl("bootout", guiDomain()+"/"+launchdLabel(name))
	return err
}

func (l launchd) verb(verb, name string) error {
	target := guiDomain() + "/" + launchdLabel(name)
	run := func(args ...string) error {
		if out, err := launchctl(args...); err != nil {
			return fmt.Errorf("launchctl %s: %v: %s", strings.Join(args, " "), err, strings.TrimSpace(string(out)))
		}
		return nil
	}
	switch verb {
	case "start":
		// Loaded already, or not since a stop or a login: bootstrap, whose
		// "already loaded" error is not one, then kickstart.
		if p, err := l.path(name); err == nil {
			_, _ = launchctl("bootstrap", guiDomain(), p)
		}
		return run("kickstart", target)
	case "stop":
		// SIGTERM: dund exits 0, and SuccessfulExit=false leaves it stopped
		// but loaded, so `start` brings it back.
		return run("kill", "SIGTERM", target)
	case "restart":
		return run("kickstart", "-k", target)
	case "status":
		cmd := exec.Command("launchctl", "print", target)
		cmd.Stdout, cmd.Stderr = os.Stdout, os.Stderr
		return cmd.Run()
	}
	return fmt.Errorf("no service verb %s", verb)
}

func (launchd) logs(_, home string) error {
	cmd := exec.Command("tail", "-n", "80", "-F", filepath.Join(home, "dund.log"))
	cmd.Stdout, cmd.Stderr = os.Stdout, os.Stderr
	return cmd.Run()
}

// ServicePATH is the PATH the installed service runs with, as its file
// says, and whether the file sets one.
func ServicePATH(name string) (string, bool) {
	p, ok := ServiceFile(name)
	if !ok {
		return "", false
	}
	b, err := os.ReadFile(p)
	if err != nil {
		return "", false
	}
	s := string(b)
	if _, isLaunchd := serviceManager().(launchd); isLaunchd {
		_, rest, found := strings.Cut(s, "<key>PATH</key><string>")
		if !found {
			return "", false
		}
		v, _, _ := strings.Cut(rest, "</string>")
		return html.UnescapeString(v), true
	}
	for _, line := range strings.Split(s, "\n") {
		v, found := strings.CutPrefix(line, "Environment=")
		if !found {
			continue
		}
		v = strings.Trim(v, `"`)
		if path, ok := strings.CutPrefix(v, "PATH="); ok {
			return strings.NewReplacer(`\"`, `"`, `\\`, `\`, `%%`, `%`).Replace(path), true
		}
	}
	return "", false
}
